test('second configured goal completes and resumes identically', () => {
  const a = runGoal(goalSession('indefinite', IND, T), structuredLearner({}, []));
  const b = runGoal(goalSession('indefinite', IND, T), structuredLearner({}, []), { reloadEvery: true });
  assert.deepEqual(b.steps, a.steps);
  assert.equal(goalState(a.s).records.pathway?.target, IND);
  assert.ok(a.steps.length > 0);
  assert.equal(goalState(a.s).next?.kind, 'none');
  assert.equal(goalState(goalSession('original', OWN, T)).records.pathway?.target, OWN);
});
test('resolved recovery offers one fresh check without erasing history or awarding mastery', () => {
  const s = new SliceSession('educator-reentry', OWN, T);
  const original = moduleFor(OWN)!.diagnostics[0];
  s.submit(original, '1', 'diagnostic');
  const ack = { id: 'ack-1', at: new Date(s.now + 1000).toISOString(), competency: OWN, by: 'educator' as const, recoveryEpisode: `deep:${original}#${s.state().records.attempts[0].at}` };
  s.now += 2000;
  s.acknowledgements = [ack];
  s.session = `learn:${s.learnerId}:reentry`;
  let st = s.state(), records = { ...st.records, acknowledgements: [ack] };
  const ms = deepModuleState(true, OWN, records, st.evidence(OWN), s.now, s.session, null, st.evidence);
  assert.equal(ms.phase, 'reentry');
  assert.notEqual(problemKeyOf(ms.question!), problemKeyOf(original));
  assert.equal(ms.context, `reentry:${OWN}`);
  assert.equal(records.attempts.length, 1);
  const request = { operation: "reentry" as const, learner: s.learnerId, competency: OWN, questionId: ms.question!, now: s.now, sessionId: s.session, events: withDecisions(s.events, s.decisions), acknowledgements: [ack] };
  assert.equal(reentryEligibility(request).allowed, true);
  assert.equal(reentryEligibility({ ...request, questionId: original }).allowed, false);
  assert.equal(reentryEligibility({ ...request, acknowledgements: [] }).allowed, false);
  s.submit(ms.question!, question(ms.question!).answer, 'diagnostic', { context: ms.context! });
  st = s.state(); records = { ...st.records, acknowledgements: [ack] };
  assert.notEqual(moduleState(OWN, records, st.evidence(OWN), s.now, s.session, null, st.evidence).phase, 'reentry');
  assert.equal(records.attempts.length, 2);
  const ah = afterHelpOf(OWN, records, st.evidence, s.now)!;
  assert.equal(ah.episode, 'educator:ack-1');
  assert.equal(ah.unaided[0].questionId, ms.question);
  assert.equal(ah.kind, 'after-help');
  assert.equal(reentryEligibility({ ...request, now: s.now, events: withDecisions(s.events, s.decisions) }).allowed, false);
  s.now += 3 * 3600000;
  const later = moduleFor(OWN)!.diagnostics.find(q => problemKeyOf(q) !== problemKeyOf(original) && problemKeyOf(q) !== problemKeyOf(ms.question!))!;
  s.submit(later, '999', 'diagnostic');
  const failed = s.state();
  const retained = afterHelpOf(OWN, failed.records, failed.evidence, s.now)!;
  assert.equal(retained.kind, 'after-help-later-wrong');
  assert.deepEqual(retained.unaided, ah.unaided);
  assert.notEqual(st.evidence(OWN).status, 'verified');
});

test('second goal reuses deep recovery through exponents and returns to fresh unaided problems', () => {
  const exp = "MATH.number.exponents";
  const learner = () => withBugs(structuredLearner({ "fam:pint": [exp] }, [exp]));
  const a = runGoal(goalSession("second-gap", IND, T), learner());
  const b = runGoal(goalSession("second-gap", IND, T), learner(), { reloadEvery: true });
  assert.deepEqual(a.steps, b.steps);
  assert.ok(a.steps.some(s => s.where === "deep" && s.lesson === exp));
  const returns = a.steps.filter(s => s.where === "deep" && s.phase === "return");
  assert.equal(returns.length, 2);
  assert.ok(returns.every(s => s.correct));
  assert.notEqual(problemKeyOf(returns[0].qid!), problemKeyOf(returns[1].qid!));
  const st = goalState(a.s);
  assert.equal(afterHelpOf(IND, st.selectionRecords, st.selectionEvidence, a.s.now)?.kind, "after-help");
});

test('a later failure keeps the earlier success visible in Year without contributing mastery', () => {
  const st = goalState(goalSession("year-failure", OWN, T));
  const ev = (id: string) => ({ ...st.evidence(id), status: "review" as const });
  const raw = tilesFor(st.release!, ev);
  const before = JSON.stringify(raw);
  const ah = { kind: "after-help-later-wrong", label: AFTER_HELP } as AfterHelp;
  const tiles = afterHelpTiles(raw, () => ah);
  const totals = afterHelpSummary(tiles);
  assert.ok(totals.afterHelp > 0);
  assert.equal(totals.shown, 0);
  assert.equal(totals.verified, 0);
  assert.equal(totals.progress, 0);
  assert.equal(JSON.stringify(raw), before);
});
