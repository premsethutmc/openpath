/**
 * Writes docs/mathematics/CTS_ADAPTIVE_JOURNEYS.md: every decision of the six synthetic journeys, with the questions,
 * responses and resulting state. Regenerate after changing the unit or its help:
 *   cd frontend && node --import tsx src/mathematics/unit/journeys-report.ts
 */
import { writeFileSync } from "node:fs";
import { question, standing, unit } from "../../../../packages/mathematics/src/unit";
import { rule } from "../../../../packages/mathematics/src/remediation";
import { JOURNEYS, run, type TraceEntry } from "./journeys";

const EVENT: Record<TraceEntry["event"], string> = {
  answer: "answer",
  "first-difficulty": "first difficulty",
  teach: "help: teach",
  guided: "help: guided (assisted)",
  check: "help: check alone",
  diagnose: "diagnosis: quick question",
  pause: "help: pause",
  skip: "help set aside",
};
const stageNo = (id: string) => unit.stages.findIndex((s) => s.id === id) + 1;
const cell = (t: string) => t.replace(/\|/g, "\\|").replace(/\n/g, " ");
const out: string[] = [
  "# Completing the square: adaptive help, six synthetic journeys",
  "",
  "Generated by `frontend/src/mathematics/unit/journeys-report.ts` from the same driver the tests use (`journeys.ts`). Each journey plays the whole unit the way the screens do. The learners are rules, not people: **this shows what the program does, not that anyone learns from it.**",
  "",
  "In each table:",
  "",
  "* **What happened** is either an answer in the program, the help given at a first difficulty, or a step of a help branch.",
  "* **The learner is told** is the unit's own wording.",
  "* **Planner** is the shared planner's decision and reason, exactly as it returned them. Its wording comes from the English rules and is kept for audit only; the learner never sees it.",
  "",
  "Only wrong answers and help steps are listed. Right answers in the program are left out.",
  "",
];
for (const j of JOURNEYS) {
  const r = run(j);
  const st = standing(r.state, { status: r.profileStatus });
  out.push(`## ${j.title}`, "", `**Expected:** ${j.expected}.`, "");
  const rows = r.trace.filter((t) => t.event !== "answer" || t.correct === false);
  if (!rows.length) out.push("No help branch opened, no first-difficulty help: every answer was right.", "");
  else {
    out.push("| Visit | Step | What happened | Rule / strategy | Question | Response | Right? | The learner is told | Planner |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
    for (const t of rows)
      out.push(`| ${t.visit} | ${stageNo(t.stage)} | ${EVENT[t.event]} | ${t.rule ? `${rule(t.rule).name}${t.strategy ? ` / ${t.strategy.replace(/_/g, " ")}` : ""}` : ""} | ${t.question ? cell(`${t.question}: ${question(t.question).prompt}`) : ""} | ${t.response ?? ""} | ${t.correct === undefined ? "" : t.correct ? "yes" : "no"} | ${cell(t.reason ?? "")} | ${cell(t.planner ?? "")} |`);
    out.push("");
  }
  const outcomes = Object.entries(r.outcomes).filter(([, o]) => o !== "none");
  out.push("**Resulting state:**", "");
  out.push(`* **Steps done:** ${r.state.completed.length} of ${unit.stages.length}.`);
  out.push(`* **Shown on your own** (independent, application, transfer and revision steps): ${st.demonstrated.correct} of ${st.demonstrated.answered}.`);
  out.push(`* **Verified mastery:** ${st.verified ? "yes" : "no (provisional content)"}.`);
  out.push(`* **Help outcomes:** ${outcomes.length ? outcomes.map(([k, o]) => `${rule(k).name}: ${o.replace(/-/g, " ")}`).join("; ") : "none"}.`);
  if (r.resumedWith) out.push(`* **On return:** the program reopened ${r.resumedWith.branch ? `the unfinished help (its ${r.resumedWith.branch})` : "the lesson"}. The lesson's own position was unchanged: step ${stageNo(r.resumedWith.stage)}, part ${r.resumedWith.part + 1}.`);
  out.push(`* **Records:** ${r.events.length} records were saved, including ${r.state.attempts.length} answers; every attempt is kept.`, "");
}
writeFileSync(new URL("../../../../docs/mathematics/CTS_ADAPTIVE_JOURNEYS.md", import.meta.url), out.join("\n"));
console.log("wrote docs/mathematics/CTS_ADAPTIVE_JOURNEYS.md");
