// ---------------------------------------------------------------- scoring

export interface MeaningMatch {
  id: string;
  score: number;
  shared: string[];
}
export interface MeaningMapping {
  method: "meaning@2" | "meaning@3" | "meaning@4";
  concepts: string[];
  candidates: MeaningMatch[];
  /** clear: one competency stands out; uncertain: a reviewer must choose; missing: no competency carries it. */
  verdict: "clear" | "uncertain" | "missing";
  why: string;
}
export const MEANING_POLICY = {
  // concept scoring (meaning@3)
  gradePenalty: 0.06,
  contradiction: 0.5,
  // exemplars (meaning@4)
  wordWeight: 0.55,
  gradeDecay: 0.2,
  neighbours: 5,
  exemplarWeight: 0.9,
  shareWeight: 0.5,
  floor: 0.15,
  clearAt: 0.35,
  margin: 0.12,
  conceptClearAt: 0.75,
  conceptMargin: 0.12,
} as const;
/** Qualifiers: a competency that carries one the outcome does not mention is a different, narrower skill. */
const QUALIFIERS = ["geometric", "inverse", "applications", "unlikeDenominators", "twoVariables", "vectors", "complexNumbers", "solids", "matrices", "byParts", "substitution", "firstPrinciples", "extrema", "binomialTheorem"];
/** Concepts that cannot both describe one outcome: a competency carrying the other one is penalised. */
const CONTRADICTIONS: [string, string][] = [["likeDenominators", "unlikeDenominators"], ["area", "perimeter"], ["multiDigit", "facts"], ["rounding", "estimation"], ["oneVariable", "twoVariables"]];

function conceptScore(o: Set<string>, c: Competency, grade: number) {
  const s = signature.get(c.id)!;
  const shared = [...o].filter((k) => s.has(k));
  const w = (ks: Iterable<string>) => [...ks].reduce((a, k) => a + (idf.get(k) ?? 0), 0);
  if (!shared.length || !s.size) return { score: 0, shared };
  const coverage = w(shared) / w(o);
  const precision = w(shared) / w(s);
  const [lo, hi] = c.gradeRange;
  const distance = grade < lo ? lo - grade : grade > hi ? grade - hi : 0;
  const qualifierMismatch = QUALIFIERS.some((q) => s.has(q) && !o.has(q));
  const contradicts = qualifierMismatch || CONTRADICTIONS.some(([x, y]) => (o.has(x) && s.has(y) && !s.has(x)) || (o.has(y) && s.has(x) && !s.has(y)));
  return { score: Math.max(0, 0.6 * coverage + 0.4 * precision - MEANING_POLICY.gradePenalty * distance - (contradicts ? MEANING_POLICY.contradiction : 0)), shared };
}

export interface InterpretOptions {
  /** Leave exemplars out, by exemplar id and source file (evaluation: an outcome is never its own exemplar). */
  exclude?: (e: { id: string; source: string }) => boolean;
}
/** The nearest reviewed outcomes: similarity of content words and concepts, discounted by grade distance. */
export function neighbours(outcome: string, grade: number, options: InterpretOptions = {}) {
  const P = MEANING_POLICY;
  const qw = contentWords(outcome);
  const qk = [...concepts(outcome)];
  const qwn = norm(qw, wordIdf);
  const qkn = norm(qk, conceptIdf);
  const out: { e: Exemplar; sim: number; weight: number }[] = [];
  for (const e of exemplars) {
    if (options.exclude?.(e)) continue;
    let wd = 0;
    for (const x of qw) if (e.words.includes(x)) wd += wordIdf(x) ** 2;
    let kd = 0;
    for (const x of qk) if (e.concepts.includes(x)) kd += conceptIdf(x) ** 2;
    // sharing only a process concept (explain, prove, solve word problems …) and no word is not a likeness
    if (!wd && !qk.some((x) => !PROCESS.has(x) && e.concepts.includes(x))) continue;
    const wc = qwn && e.wordNorm ? wd / (qwn * e.wordNorm) : 0;
    const kc = qkn && e.conceptNorm ? kd / (qkn * e.conceptNorm) : 0;
    const sim = qk.length || e.concepts.length ? P.wordWeight * wc + (1 - P.wordWeight) * kc : wc;
    out.push({ e, sim, weight: sim * Math.exp(-P.gradeDecay * (grade < e.lo ? e.lo - grade : grade > e.hi ? grade - e.hi : 0)) });
  }
  return out.sort((a, b) => b.weight - a.weight || a.e.id.localeCompare(b.e.id)).slice(0, P.neighbours);
}

const r3 = (x: number) => Math.round(x * 1000) / 1000;
/** Every competency scored for an outcome, best first (interpret() decides the verdict from this ranking). */
export function rank(outcome: string, grade: number, options: InterpretOptions = {}) {
  const P = MEANING_POLICY;
  const o = concepts(outcome);
  const near = neighbours(outcome, grade, options);
  const total = near.reduce((a, n) => a + n.weight, 0);
  const vote = new Map<string, { share: number; best: number }>();
  for (const n of near)
    for (const c of n.e.competencies) {
      const v = vote.get(c) ?? { share: 0, best: 0 };
      v.share += n.weight / total;
      v.best = Math.max(v.best, n.weight);
      vote.set(c, v);
    }
  const ranked = mapped
    .map((c) => {
      const k = o.size ? conceptScore(o, c, grade) : { score: 0, shared: [] };
      const v = vote.get(c.id) ?? { share: 0, best: 0 };
      const ex = v.best * (1 - P.shareWeight + P.shareWeight * v.share);
      // an outcome naming mathematics no competency carries is not forced onto a skill that shares only its words
      const gap = !k.shared.length && [...o].some((x) => GAPS.has(x));
      const score = gap ? 0 : P.exemplarWeight * ex + (1 - P.exemplarWeight) * k.score;
      return { id: c.id, score: r3(score), shared: k.shared, exemplar: ex, share: v.share, concept: k.score };
    })
    .filter((m) => m.score > 0)
    .sort((a, b) => b.score - a.score || a.id.localeCompare(b.id));
  // the concept scoring's own verdict (meaning@3): its best competency, and by how much it leads
  const byConcept = [...ranked].sort((a, b) => b.concept - a.concept || a.id.localeCompare(b.id));
  const conceptLead = byConcept[0] && byConcept[0].concept >= P.conceptClearAt && byConcept[0].concept - (byConcept[1]?.concept ?? 0) >= P.conceptMargin ? byConcept[0].id : null;
  return { concepts: o, near, ranked, conceptLead };
}

export function interpret(outcome: string, grade: number, limit = 3, options: InterpretOptions = {}): MeaningMapping {
  const P = MEANING_POLICY;
  const { concepts: o, near, ranked, conceptLead } = rank(outcome, grade, options);
  const candidates = ranked.filter((m) => m.score >= P.floor).slice(0, limit);
  const found = [...o];
  if (!candidates.length) return { method: "meaning@4", concepts: found, candidates: [], verdict: "missing", why: found.length ? `No competency covers ${found.join(", ")}.` : "No mathematical concept was recognised in this outcome." };
  const [a, b] = candidates;
  // clear only when one skill stands out AND the nearest reviewed outcome was mapped to it: a confident wrong answer
  // costs a learner more than a reviewer's question
  const like = near.find((n) => n.e.competencies.includes(a.id));
  const byExemplars = a.score >= P.clearAt && (!b || a.score - b.score >= P.margin) && !!like && like === near[0];
  // or: the concepts alone single it out (as meaning@3 would say "clear") and the exemplars rank it first too
  const byConcepts = conceptLead === a.id && !!like && like === near[0];
  // but when the runner-up carries a concept of the outcome that the first does not, and the nearest reviewed outcome was
  // mapped to both, the outcome is two skills ("divide and interpret the remainder"): a reviewer chooses
  const both = !!b && b.shared.some((k) => !a.shared.includes(k)) && !!like && like.e.competencies.includes(b.id);
  const clear = (byExemplars || byConcepts) && !both;
  return {
    method: "meaning@4",
    concepts: found,
    candidates: candidates.map(({ id, score, shared }) => ({ id, score, shared })),
    verdict: clear ? "clear" : "uncertain",
    why: clear
      ? `Matches on ${[...a.shared, like!.e.source === "graph" ? "the skill's own wording" : `a reviewed outcome (${like!.e.id})`].join(", ")}.`
      : both
        ? `The outcome spans two skills (${graph.get(a.id).name}; ${graph.get(b.id).name}): a reviewer should choose.`
        : b && a.score - b.score < P.margin
        ? `Two skills are close (${graph.get(a.id).name}; ${graph.get(b.id).name}): a reviewer should choose.`
        : `A weak match (${graph.get(a.id).name}): a reviewer should confirm.`,
  };
}
