/** Function words and words every outcome uses; they say nothing about which mathematics is meant. */
const STOP = new Set(
  "a an and the of to in on with by for from into as or at up is are be its their this that these those it they them such e g eg etc i ie including include includes simple given giving various each both also how what which when where why who whose than then there so if can will learner learners student students pupils child children able understand understanding know knowledge appropriate related relevant using use uses used".split(" "),
);
/** A light, deterministic stemmer: plural and verb endings, a final e, then the first seven letters
 * (dividing / divide / divides → divid; triangle / triangles / triangular → triangl). */
export function stem(w: string): string {
  let s = w;
  if (s.length > 4 && s.endsWith("ies")) s = `${s.slice(0, -3)}y`;
  else if (s.length > 3 && s.endsWith("s") && !/(ss|us|is)$/.test(s)) s = s.slice(0, -1);
  if (s.length > 5 && s.endsWith("ing")) s = s.slice(0, -3);
  else if (s.length > 4 && s.endsWith("ied")) s = `${s.slice(0, -3)}y`;
  else if (s.length > 4 && s.endsWith("ed")) s = s.slice(0, -2);
  if (s.length > 3 && s.endsWith("e")) s = s.slice(0, -1);
  return s.slice(0, 7);
}
export function contentWords(text: string): string[] {
  const t = text.toLowerCase().replace(/['’]s\b/g, "").replace(/[^a-z0-9]+/g, " ");
  return [...new Set(t.split(" ").filter((w) => w && !STOP.has(w) && !/^\d+$/.test(w)).map(stem))];
}

