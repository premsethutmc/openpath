/**
 * Curriculum interpretation by mathematical meaning (mapping@2; meaning@3 adds secondary-school concepts and the
 * competency concept annotations of content/learning/competency-concepts.v1.json; meaning@4 adds labelled exemplars).
 * Deterministic and offline: no language model, no network, the same answer for the same text every time.
 *
 * CONCEPTS. An outcome and a competency are each read into concepts: the mathematical objects, operations and relations
 * they talk about (fraction, equivalence, comparison, mass, capacity, clock, symmetry, matrices, …), recognised through
 * synonyms, symbols and typical school phrasings ("the same amount", "which is bigger", "the distance around", "left
 * over"). The concept score of a competency = coverage of the outcome's concepts (weighted by how rare each concept is
 * across the competency map) and precision against the competency's concepts, minus a grade-distance penalty, with
 * qualifier and contradiction penalties (meaning@3).
 *
 * EXEMPLARS (meaning@4). The hand-checked curriculum inventory (content/learning/syllabus/*.json: CBSE and Tamil Nadu,
 * Grades 1–12) is an index of labelled exemplars (content/learning/mapping-exemplars.v1.json, GENERATED by
 * packages/learning/scripts/mapping-exemplars.ts): each reviewed outcome's stemmed content words, concepts, grade and
 * the competencies it maps to; each competency's own wording (name, description, objectives) is an exemplar of it
 * too. An outcome's nearest exemplars are found by idf-weighted cosine similarity of words (55%) and concepts (45%),
 * discounted by grade distance (e^-0.2 per grade); two outcomes sharing only a process concept (explain, prove, word
 * problems) and no word are not alike. The five nearest vote: a competency's exemplar score is its best neighbour's
 * similarity, scaled by its share of the vote. Score = 90% exemplar score + 10% concept score.
 *
 * VERDICT. CLEAR only when the top competency leads (score ≥ 0.35 and 0.12 ahead of the runner-up, or the concepts
 * alone single it out as meaning@3's "clear" would) AND the single nearest reviewed outcome was mapped to it, and the
 * outcome is not two skills (the runner-up carries a concept of the outcome the first does not, and the nearest
 * reviewed outcome was mapped to both). Otherwise UNCERTAIN: a reviewer must choose; a confident wrong answer costs a
 * learner more than a reviewer's question. MISSING when no competency scores at least 0.15, or when the outcome names
 * a concept no competency carries (a timetable) and a candidate shares none of its concepts: a provisional proposal
 * with its source reference, never forced onto a skill. Nothing is authoritative until reviewed.
 *
 * Measured against the inventory with exemplars held out (frontend/src/learning/mapping.test.ts): top-1 agreement
 * 76% leaving the outcome out, 76% leaving its whole book out, 74% leaving its whole board out (meaning@3: 37%);
 * clear but wrong for about 5% of outcomes (meaning@3: 11%).
 */
