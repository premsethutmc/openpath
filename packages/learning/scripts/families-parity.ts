/** Write content/learning/families-parity.v1.json: generated question ids with what the app accepts, for the server's test. */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { FAMILIES, problemOf, variantsOf } from "../src/families";

const ids = new Set<string>();
for (const [fam, def] of FAMILIES) {
  const seed = { mul: [7, 8], rect: [7, 6], eqfrac: [2, 5, 15], fadd: [3, 2, 8, 1], cint: [2, 9, 6], quad: [-5, 6], linev: [2, 3, 4], meet: [1, 2], above: [1, 2, 0], alp: [1, 2] }[fam]!;
  ids.add(`gen:${fam}:${seed.join(",")}`);
  const p = problemOf(`gen:${fam}:${seed.join(",")}`);
  if (p) for (const v of variantsOf(p).slice(0, 25)) ids.add(v.id);
  void def;
}
for (const bad of ["gen:mul:13,2", "gen:mul:7", "gen:eqfrac:2,5,14", "gen:fadd:3,2,8,1,9", "gen:cint:5,2,3", "gen:quad:1,1", "gen:alp:1,1", "gen:meet:0,0", "gen:above:1,2,2", "gen:nope:1,2", "gen:mul:7,8,9", "gen:mul:a,b"]) ids.add(bad);
const rows = [...ids].map((id) => {
  const p = problemOf(id);
  return p ? { id, supported: true, competency: p.competency, type: p.type, answer: p.answer } : { id, supported: false };
});
writeFileSync(join(import.meta.dirname, "../../../content/learning/families-parity.v1.json"), JSON.stringify({ note: "Generated by packages/learning/scripts/families-parity.ts; the server (backend/family/learning_families.py) must agree.", rows }, null, 1) + "\n");
console.log(rows.length, rows.filter((r) => r.supported).length);
