/**
 * teaching-review@1: every piece of teaching the owner approves on the dashboard (/review/ → Teaching), as data.
 *   recipe:<skill>  a written story lesson (recipe.ts, recipes-class5.ts)
 *   card:<skill>    a help card made by rule from the skill's own lesson (cardFor in step-help.ts)
 * Each item carries the hash of exactly what a learner is shown, so a decision applies to that version only; `from`
 * says which part of the lesson a card's rule was taken from. Written to content/learning/teaching.v1.json. `--check` fails if out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { allReleases } from "../src/curricula.ts";
import { assigned, hashOf } from "../src/curriculum.ts";
import { graph } from "../src/graph.ts";
import { ALL_RECIPES } from "../src/recipe.ts";
import { cardFor } from "../src/step-help.ts";

const FILE = new URL("../../../content/learning/teaching.v1.json", import.meta.url);
const BOARD: [RegExp, string][] = [[/^icse-/, "ICSE"], [/^cbse-/, "CBSE"], [/^tn-/, "TN"]];
const classes = new Map<string, Set<string>>();
for (const r of allReleases.filter((r, _i, a) => !a.some((x) => x.id === r.id && x.version > r.version))) {
  const board = BOARD.find(([re]) => re.test(r.id))?.[1];
  if (!board) continue; // sample and test releases are not a class a family picks
  for (const a of assigned(r)) (classes.get(a.competency) ?? classes.set(a.competency, new Set()).get(a.competency)!).add(`${board} ${r.grade}`);
}
const order = (a: string, b: string) => Number(a.split(" ")[1]) - Number(b.split(" ")[1]) || a.localeCompare(b);
const classesOf = (c: string) => [...(classes.get(c) ?? [])].sort(order);
const items: Record<string, unknown>[] = [];
for (const r of ALL_RECIPES) items.push({ item: `recipe:${r.competency}`, kind: "recipe", competency: r.competency, title: r.title, hash: hashOf(r), source: "written", classes: classesOf(r.competency) });
for (const c of [...graph.byId.keys()].sort()) {
  const card = cardFor(c);
  if (card) items.push({ item: `card:${c}`, kind: "card", competency: c, title: card.name, hash: hashOf(card), source: "rule", from: card.source, classes: classesOf(c) });
}
const out = JSON.stringify({ schema: "teaching-review@1", note: "Generated by packages/learning/scripts/teaching.ts (node tools/regen.mjs). Do not edit.", items }, null, 1) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(FILE, "utf8") !== out) { console.error("teaching.v1.json is out of date: run node tools/regen.mjs"); process.exit(1); }
} else writeFileSync(FILE, out);
const n = (k: string) => items.filter((i) => i.kind === k).length;
console.log(`teaching-review@1: ${n("recipe")} recipes, ${n("card")} cards`);
