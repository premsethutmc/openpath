/**
 * lesson-checks@1 (src/lesson-checks.ts): the review findings, checked automatically on every lesson of a grade, as a learner
 * of that grade sees it.
 *
 *   bun packages/learning/scripts/lesson-checks.ts                       grades 7 and 8, both boards: counts, then findings
 *   … --grade 8 --board tn [--check mixed-example] [--all]                one grade / board / check; --all lists every finding
 *   … --write-baseline                                                    write content/learning/lesson-checks-baseline.v1.json
 *                                                                        (after a fix: counts may only fall; the test enforces it)
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { moduleFor } from "../src/content";
import { boardFor } from "../src/curricula";
import { allOutcomesOf } from "../src/curriculum";
import { graph } from "../src/graph";
import { CHECKS, countByCheck, lessonChecks, type CheckId, type Finding } from "../src/lesson-checks";

export const BASELINE_FILE = join(import.meta.dirname, "../../../content/learning/lesson-checks-baseline.v1.json");
export const SCOPE = [7, 8].flatMap((grade) => (["cbse", "tn"] as const).map((board) => ({ grade, board })));
/** The competencies a grade's release asks for (as the grade coverage tests read them). */
export function competenciesOf(board: "cbse" | "tn", grade: number): string[] {
  const r = boardFor(board, grade);
  if (!r) return [];
  return [...new Set(allOutcomesOf(r).flatMap(({ outcome }) => outcome.mapping.competencies.filter((m) => m.status === "accepted").map((m) => (graph.byId.has(m.id) ? graph.evidenceTarget(m.id) : m.id))))].sort();
}
export function findingsFor(board: "cbse" | "tn", grade: number): Finding[] {
  return competenciesOf(board, grade).flatMap((c) => { const m = moduleFor(c); return m ? lessonChecks(m, grade) : []; });
}

// run as a command (bun or node), not when a test imports it
if (/lesson-checks\.ts$/.test(process.argv[1] ?? "")) {
  const argv = process.argv.slice(2);
  const val = (k: string) => { const i = argv.indexOf(`--${k}`); return i >= 0 ? argv[i + 1] : undefined; };
  const only = val("check") as CheckId | undefined;
  const scope = SCOPE.filter((s) => (!val("grade") || s.grade === Number(val("grade"))) && (!val("board") || s.board === val("board")));
  const counts: Record<string, Record<CheckId, number>> = {};
  for (const { grade, board } of scope) {
    const fs = findingsFor(board, grade);
    counts[`${board}-g${grade}`] = countByCheck(fs);
    console.log(`\n== ${board.toUpperCase()} Grade ${grade}: ${fs.length} findings ==`);
    for (const [c, n] of Object.entries(countByCheck(fs))) if (n && (!only || c === only)) {
      console.log(`${String(n).padStart(4)}  ${c}: ${CHECKS[c as CheckId]}`);
      for (const f of fs.filter((x) => x.check === c).slice(0, argv.includes("--all") ? Infinity : 3)) console.log(`        ${f.competency}${f.section ? ` · ${f.section}` : ""}: ${f.detail.slice(0, 160)}`);
    }
  }
  if (argv.includes("--write-baseline")) {
    if (scope.length !== SCOPE.length) throw new Error("--write-baseline needs the whole scope (no --grade / --board)");
    writeFileSync(BASELINE_FILE, JSON.stringify({ note: "GENERATED by packages/learning/scripts/lesson-checks.ts --write-baseline: lesson-checks@1 finding counts per board and grade. Counts may only fall: lesson-checks.test.ts fails when one rises. Lower them by fixing content, then rewrite this file.", counts }, null, 1) + "\n");
    console.log(`\nwrote ${BASELINE_FILE}`);
  }
}
