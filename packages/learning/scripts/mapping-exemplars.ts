/**
 * Write the mapping exemplar index (GENERATED; a test checks it is current):
 *
 *   content/learning/mapping-exemplars.v1.json   every reviewed outcome of the curriculum inventory
 *                                                (content/learning/syllabus/*.json): its content words (stemmed),
 *                                                its concepts, its grade and the competencies it was mapped to
 *
 * meaning@4 (packages/learning/src/meaning.ts) scores an outcome's candidate competencies by its nearest exemplars
 * together with the concept scoring. Regenerate after changing the inventory, the lexicon or the stemmer:
 *
 *   node --import tsx packages/learning/scripts/mapping-exemplars.ts
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { exemplarOf, MEANING_VERSION, type ExemplarRow } from "../src/meaning";

const root = join(import.meta.dirname, "../../../content/learning");

/** Every reviewed outcome of the inventory, in file and book order. */
export function exemplarRows(): ExemplarRow[] {
  const rows: ExemplarRow[] = [];
  for (const f of readdirSync(join(root, "syllabus")).filter((x) => /^(cbse|tn)-g\d\d\.json$/.test(x)).sort()) {
    const s = JSON.parse(readFileSync(join(root, "syllabus", f), "utf8")) as { grade: number; chapters: { outcomes: { id: string; statement: string; mapped?: string[] }[] }[] };
    for (const ch of s.chapters) for (const o of ch.outcomes) if (o.mapped?.length) rows.push(exemplarOf(o.id, o.statement, s.grade, o.mapped));
  }
  return rows;
}
export function exemplarIndex() {
  return {
    schema: "mapping-exemplars@1",
    note: `GENERATED by packages/learning/scripts/mapping-exemplars.ts from content/learning/syllabus/*.json, for ${MEANING_VERSION}. Each row: [outcome id, grade, stemmed content words, concepts, competencies the inventory maps it to]. The inventory mappings were checked by hand; they are not educator-reviewed.`,
    exemplars: exemplarRows(),
  };
}
export const serialise = (index: ReturnType<typeof exemplarIndex>) => `{\n "schema": ${JSON.stringify(index.schema)},\n "note": ${JSON.stringify(index.note)},\n "exemplars": [\n${index.exemplars.map((r) => `  ${JSON.stringify(r)}`).join(",\n")}\n ]\n}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const index = exemplarIndex();
  writeFileSync(join(root, "mapping-exemplars.v1.json"), serialise(index));
  console.log(`${index.exemplars.length} exemplars written`);
}
