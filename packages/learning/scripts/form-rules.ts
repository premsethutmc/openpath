/**
 * Write the declared answer-form rules of every family (GENERATED from the families' own question wording; a test checks it is current):
 *
 *   content/learning/form-rules.v1.json   family -> the form rules its questions state (grading/forms.ts FORM_INSTRUCTIONS), with how many
 *                                         released typed and word presentations state each. The contract builder enforces a rule for a
 *                                         question only when the family declares it here AND that question's own instruction states it.
 *
 * A change of generator wording that adds, removes or changes a form instruction changes this file, so the change is visible and reviewed.
 *   bun packages/learning/scripts/form-rules.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { FAMILIES, pool, problemOf } from "../src/families";
import { semanticsOf } from "../src/grading/parse";
import { statedRules, type FormRuleId } from "../src/grading/forms";

const families: Record<string, FormRuleId[]> = {};
const evidence: Record<string, Record<string, { stated: number; of: number; instruction: string; judgeable: boolean }>> = {};
for (const [fam, def] of FAMILIES) {
  const counts: Record<string, { stated: number; of: number; instruction: string; judgeable: boolean }> = {};
  let of = 0;
  for (const q of pool(fam).items) {
    for (const sfx of ["", ":w"]) {
      const p = sfx ? (def.word ? problemOf(q.id + sfx) : null) : q;
      if (!p || p.type === "choice") continue;
      of++;
      for (const r of statedRules(p.prompt, semanticsOf({ type: p.type, answer: p.answer }).kind)) {
        const c = (counts[r.rule] ??= { stated: 0, of: 0, instruction: r.instruction, judgeable: r.judgeable });
        c.stated++;
        if (!r.judgeable) c.judgeable = false;
      }
    }
  }
  for (const c of Object.values(counts)) c.of = of;
  const rules = Object.keys(counts).sort() as FormRuleId[];
  if (rules.length) { families[fam] = rules; evidence[fam] = counts; }
}
const hash = createHash("sha256").update(JSON.stringify(families)).digest("hex");
writeFileSync(join(import.meta.dirname, "../../../content/learning/form-rules.v1.json"), JSON.stringify({ schema: "form-rules@1", note: "GENERATED by packages/learning/scripts/form-rules.ts from the families' question wording. Reviewed in the pull request that changes it.", hash, families, evidence }, null, 1) + "\n");
console.log(Object.keys(families).length, "families declare form rules", hash.slice(0, 12));
