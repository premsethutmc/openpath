/**
 * child-lab@1: runs every lab scenario and writes the scorecard the owner sees at /owner/#lab
 * (content/owner/child-lab.v1.json) and the full traces (docs/audits/child-lab-traces.txt).
 *   node --import tsx packages/learning/scripts/child-lab.ts
 * A scenario recorded as passing that now fails is a regression: the script stops and writes nothing. A known gap that now
 * passes becomes "pass" (so it is held from then on).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { SCENARIOS, runScenario } from "../src/lab/scenarios";

const FILE = new URL("../../../content/owner/child-lab.v1.json", import.meta.url);
type Entry = { id: string; expected: "pass" | "known-gap"; gap?: string };
let old: { scenarios: Entry[] } = { scenarios: [] };
try { old = JSON.parse(readFileSync(FILE, "utf8")); } catch { /* first run */ }
const prior = new Map(old.scenarios.map((s) => [s.id, s]));
const out = []; const traces: string[] = []; const regress: string[] = [];
for (const s of SCENARIOS) {
  const r = runScenario(s);
  const was = prior.get(s.id);
  if (was?.expected === "pass" && !r.pass) regress.push(`${s.id} ${s.title}: ${r.checks.filter((x) => !x.ok).map((x) => x.name).join("; ")}`);
  const expected = r.pass ? "pass" : (was?.expected ?? "known-gap");
  out.push({ id: r.id, title: r.title, child: r.child, expected, ...(expected === "known-gap" ? { gap: was?.gap ?? "not fixed yet" } : {}), pass: r.pass, questions: r.questions, checks: r.checks });
  traces.push(`### ${r.id} ${r.title}\nchild: ${r.child}\n${r.checks.map((x) => `${x.ok ? "✓" : "✗"} ${x.name}`).join("\n")}\n${r.trace}\n`);
  console.log(`${r.id} ${r.pass ? "pass" : "FAIL"} (${r.questions} questions)`);
}
if (regress.length) { console.error(`child-lab@1: regression, nothing written:\n${regress.join("\n")}`); process.exit(1); }
writeFileSync(FILE, JSON.stringify({ schema: "child-lab@1", note: "GENERATED by packages/learning/scripts/child-lab.ts. Simulated children with real step-level slips, run through the app with default settings. Engineering evidence only: it shows how the app behaves, not that a child learns.", scenarios: out }, null, 1) + "\n");
writeFileSync(new URL("../../../docs/audits/child-lab-traces.txt", import.meta.url), traces.join("\n"));
