/**
 * The content-production pipeline, step 2: synthesise every blueprint (content/learning/blueprints.v1.json) into a
 * module, validate it, and write content/learning/library.v1.json. Step 3 is review (scripts/review.ts): nothing is
 * approved or released here.
 *
 *   node --import tsx packages/learning/scripts/library.ts
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { synthesise, type Blueprint } from "../src/library";
import { validateModule } from "../src/validate";

const root = join(import.meta.dirname, "../../../content/learning");
const bps = JSON.parse(readFileSync(join(root, "blueprints.v1.json"), "utf8")) as { version: string; blueprints: Blueprint[] };
const modules = bps.blueprints.map((b) => synthesise(b, bps.version));
const problems = modules.flatMap((m) => validateModule(m).map((p) => `${m.competency}: ${p}`));
if (problems.length) throw new Error(`Synthesised modules failed validation:\n${problems.join("\n")}`);
writeFileSync(join(root, "library.v1.json"), JSON.stringify({ schema: "module-library@1", version: bps.version, status: "draft", note: "GENERATED by packages/learning/scripts/library.ts from blueprints.v1.json: do not edit by hand. Every question is generated by a problem family and passes its independent check. Not educator-reviewed: see review.v1.json.", modules }, null, 1) + "\n");
console.log(`${modules.length} modules synthesised`);
