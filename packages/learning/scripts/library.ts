/**
 * The content-production pipeline, step 2: build every module from reusable parts and write
 * content/learning/library.v1.json.
 *
 *   blueprints     content/learning/blueprints.v1.json: teaching text a person wrote + a family (library@2)
 *   templates      a family's teaching hints alone (template@1), for every family whose competency has no module yet
 *   pools          hand-written modules get the release pool of the family that matches their competency
 *
 * Every module is validated (validate@1); its pool depth is reported (depth@1). Step 3 is review (scripts/review.ts):
 * nothing is approved or released here.
 *
 *   node --import tsx packages/learning/scripts/library.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { authoredModules } from "../src/content";
import { buildLibrary, poolDepth, type Blueprint } from "../src/library";
import { validateModule } from "../src/validate";

const root = join(import.meta.dirname, "../../../content/learning");
const bps = JSON.parse(readFileSync(join(root, "blueprints.v1.json"), "utf8")) as { version: string; blueprints: Blueprint[] };
const authored = authoredModules.map(({ pool: _p, ...m }) => m);
const { modules, fromBlueprints, fromTemplates, authoredPools, notBuilt } = buildLibrary(bps, authored);
const problems = modules.flatMap((m) => validateModule(m).map((p) => `${m.competency}: ${p}`));
if (problems.length) throw new Error(`Synthesised modules failed validation:\n${problems.join("\n")}`);
writeFileSync(join(root, "library.v1.json"), JSON.stringify({ schema: "module-library@2", version: bps.version, status: "draft", note: "GENERATED by packages/learning/scripts/library.ts from blueprints.v1.json and the families' teaching hints: do not edit by hand. Every question is generated by a problem family and passes its independent check. Not educator-reviewed: see the review registry.", modules, authoredPools, notBuilt }, null, 1) + "\n");
for (const m of [...modules, ...authoredModules.map((a) => ({ ...a, pool: authoredPools[a.competency] }))]) {
  const d = poolDepth(m);
  console.log(`${m.competency.padEnd(42)} ${"provenance" in m ? (m as { provenance: { policy: string } }).provenance.policy : "authored"} ${d ? `${d.family} ${JSON.stringify(d.counts)}${d.sufficient ? "" : ` SHORT: ${d.short.join(", ")}`}` : "no pool"}`);
}
for (const n of notBuilt) console.log(`NOT BUILT ${n.competency} (${n.family}): ${n.reason}`);
console.log(`${modules.length} modules built (${fromBlueprints.length} from blueprints, ${fromTemplates.length} from templates); ${Object.keys(authoredPools).length} hand-written modules given a pool`);
