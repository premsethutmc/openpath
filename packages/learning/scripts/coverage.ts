/**
 * Write docs/learning-year/COVERAGE.md: the coverage report (coverage@1) for every sample release and for the whole
 * competency graph. Deterministic; run after any content change:
 *
 *   node --import tsx packages/learning/scripts/coverage.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CATEGORIES, graphCoverage, releaseCoverage, UNSUPPORTED, type Category } from "../src/coverage";
import { sampleReleases } from "../src/curricula";
import { FAMILIES } from "../src/families";
import { modules } from "../src/content";
import { registry } from "../src/review";

const LABEL: Record<Category, string> = { diagnostic: "Diagnostic questions", strategies: "Teaching strategies", practice: "Practice (≥ 2)", independent: "Independent assessment", retention: "Retention check", approved: "Educator-approved" };
const pct = (a: number, b: number) => (b ? `${a}/${b} (${Math.round((100 * a) / b)}%)` : "0/0");
const g = graphCoverage();
const lines: string[] = [];
const L = (s = "") => lines.push(s);
L("# My Learning Year: curriculum and content coverage");
L();
L("Generated by `packages/learning/scripts/coverage.ts` (coverage@1). Do not edit by hand.");
L();
L("**Read this first.** The platform (curriculum synthesis, tiles, the module engine, recovery, evidence, goals) works for any supported textbook. The CONTENT does not yet cover the curriculum: most competencies have no learning module, and **no module has been approved by an educator**, so nothing can be verified mastery on real use. The numbers below are counts of content, not evidence of learning.");
L();
L("## Whole competency graph");
L();
L(`- Competencies (not counting micro-skills): **${g.total}**`);
L(`- With a complete learning module (validate@1): **${pct(g.module, g.total)}**; with an incomplete module: ${g.partial}; with none: ${g.total - g.module - g.partial}`);
L(`- Modules: ${modules.length} (hand-written ${modules.filter((m) => !("provenance" in m)).length}, synthesised from blueprints ${modules.filter((m) => "provenance" in m).length})`);
L(`- Problem families (generated questions with independent checks): ${FAMILIES.size}`);
L(`- Review registry: ${["draft", "submitted", "changes_requested", "approved", "released"].map((s) => `${s} ${registry.entries.filter((e) => e.state === s).length}`).join(", ")}`);
L();
L("| Category | Competencies |");
L("|---|---|");
for (const k of CATEGORIES) L(`| ${LABEL[k]} | ${pct(g.counts[k], g.total)} |`);
L();
L("By grade (a competency spanning grades counts in each):");
L();
L("| Grade | Competencies | Complete module | Incomplete module |");
L("|---|---|---|---|");
for (const [grade, row] of g.byGrade) L(`| ${grade} | ${row.total} | ${row.module} | ${row.partial} |`);
L();
L("## Sample releases");
L();
for (const r of sampleReleases.map(releaseCoverage).sort((a, b) => a.grade - b.grade || a.id.localeCompare(b.id))) {
  L(`### Grade ${r.grade}: ${r.title} (${r.id}@${r.version})`);
  L();
  L(`- Board: ${r.board ?? "—"}; subject: ${r.subject}${r.supported ? "" : " (NOT SUPPORTED)"}`);
  L(`- Extracted requirements: ${r.extracted.chapters} chapters, ${r.extracted.sections} sections, ${r.extracted.outcomes} outcomes, ${r.extracted.examples} worked examples, ${r.extracted.exercises} exercises`);
  L(`- Competency mappings: ${r.mapping.accepted}/${r.extracted.outcomes} outcomes mapped (accepted); proposals: clear ${r.mapping.clear}, uncertain ${r.mapping.uncertain}, missing ${r.mapping.missing} (provisional competency proposals ${r.mapping.proposals}), unsupported ${r.mapping.unsupported}`);
  L(`- Competencies assigned: ${r.counts.total}; complete module ${r.counts.module}, incomplete ${r.counts.partial}, none ${r.counts.none}`);
  L(`- ${CATEGORIES.map((k) => `${LABEL[k]} ${pct(r.counts[k], r.counts.total)}`).join("; ")}`);
  L();
  L("| Competency | Content | Origin | Review | What is missing |");
  L("|---|---|---|---|---|");
  for (const c of r.competencies) L(`| ${c.name} (\`${c.id}\`) | ${c.module === "module" ? "module" : c.module === "partial" ? "incomplete" : "**none**"} | ${c.origin ?? "—"} | ${c.review} | ${c.module === "none" ? "everything" : c.missing.join("; ") || "—"} |`);
  L();
}
L("## Explicitly unsupported");
L();
L(`- Subjects: ${UNSUPPORTED.subjects}`);
L("- Textbook formats:");
for (const f of UNSUPPORTED.formats) L(`  - ${f}`);
L("- Question types:");
for (const q of UNSUPPORTED.questionTypes) L(`  - ${q}`);
L();
L("## What \"complete module\" means");
L();
L("validate@1 (`packages/learning/src/validate.ts`): one to three diagnostic questions; at least one teaching strategy with its own guided and check questions; at least two practice questions; a transfer question; a two-question delayed check; at least two answer formats among the questions answered alone; no question used twice; every question about the module's competency (probes may ask about what it builds on). It is a structural check plus each generated question's independent mathematical check. It is not an educator review.");
writeFileSync(join(import.meta.dirname, "../../../docs/learning-year/COVERAGE.md"), lines.join("\n") + "\n");
console.log(`coverage: ${g.module}/${g.total} competencies with a complete module; ${g.counts.approved} approved`);
