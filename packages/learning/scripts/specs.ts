/**
 * Write the family specifications and the server's question table (both GENERATED; CI checks they are current):
 *
 *   content/learning/family-specs.v1.json   each family's specification, fingerprint and validation report (what an
 *                                           educator reviews and approves)
 *   content/learning/generated.v1.json      every released-pool question (both formats): competency, type and answer,
 *                                           so the server checks records against exactly the approved pool
 *
 *   node --import tsx packages/learning/scripts/specs.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { FAMILIES, pool, problemOf } from "../src/families";
import { familySpec, validateFamily } from "../src/spec";

const root = join(import.meta.dirname, "../../../content/learning");
const fams = [...FAMILIES.values()].filter((f) => f.domain).map((f) => f.id);
const specs = fams.map((f) => ({ ...familySpec(f)!, validation: validateFamily(f) }));
const bad = specs.filter((s) => !s.validation.ok);
writeFileSync(join(root, "family-specs.v1.json"), JSON.stringify({ schema: "family-spec@1", note: "GENERATED by packages/learning/scripts/specs.ts. A family is approved as a whole: an approval names its fingerprint, and any change of generator, wording, explanations, options or difficulty changes the fingerprint.", families: specs }, null, 1) + "\n");
const table: Record<string, { competency: string; type: string; fingerprint: string; items: Record<string, string> }> = {};
for (const s of specs) {
  const items: Record<string, string> = {};
  for (const p of pool(s.id).items) {
    items[p.params.join(",")] = p.answer;
    const mc = FAMILIES.get(s.id)!.mc && p.type !== "set" && p.type !== "choice" ? problemOf(`${p.id}:mc`) : null;
    if (mc) items[`${p.params.join(",")}:mc`] = mc.answer;
    if (FAMILIES.get(s.id)!.word) items[`${p.params.join(",")}:w`] = p.answer;
  }
  table[s.id] = { competency: s.competency, type: s.type, fingerprint: s.fingerprint, items };
}
writeFileSync(join(root, "generated.v1.json"), JSON.stringify({ schema: "generated-questions@1", note: "GENERATED by packages/learning/scripts/specs.ts: the release pool of every family, for the server. A key with :mc is the multiple-choice form (its answer is a letter); :w is the everyday-situation form (same answer).", families: table }) + "\n");
// answers@2: for families with the new answer types, the right answer and the predicted wrong answers of a sample of
// items, so the server's test checks it marks them exactly as the app does
const NEW = new Set(["exact", "roots", "tuple", "matrix", "interval", "ratio", "mixed", "expression", "antiderivative"]);
const parity: { id: string; type: string; answer: string; wrong: string[] }[] = [];
for (const s of specs) {
  if (!NEW.has(s.type)) continue;
  const items = pool(s.id).items;
  for (const p of items.filter((_, i) => i % Math.max(1, Math.floor(items.length / 40)) === 0).slice(0, 40)) {
    const wrong = p.bugs.flatMap((b) => (b.predict === null ? [] : Array.isArray(b.predict) ? b.predict : [b.predict])).map(String);
    parity.push({ id: p.id, type: p.type, answer: p.answer, wrong });
  }
}
writeFileSync(join(root, "marking-parity.v1.json"), JSON.stringify({ schema: "marking-parity@1", note: "GENERATED by packages/learning/scripts/specs.ts: right and predicted-wrong answers of new-type families; the server must mark them as the app does.", items: parity }) + "\n");
console.log(`${specs.length} families, ${specs.reduce((n, s) => n + s.poolSize, 0)} problems (${Object.values(table).reduce((n, t) => n + Object.keys(t.items).length, 0)} question ids, with the multiple-choice forms); ${bad.length} failing validation${bad.length ? `: ${bad.map((b) => b.id).join(", ")}` : ""}`);
if (bad.length) process.exit(1);
