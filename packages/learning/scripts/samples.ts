/**
 * Write docs/learning-year/GENERATED_SAMPLES.md: representative generated content for review outside the app: each
 * family's specification summary with its representative questions, and two template modules in full.
 *
 *   node --import tsx packages/learning/scripts/samples.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { modules, question } from "../src/content";
import { explainStep, FAMILIES, problemOf } from "../src/families";
import { poolDepth } from "../src/library";
import { familySpec } from "../src/spec";

const L: string[] = [];
const w = (s = "") => L.push(s);
w("# Representative generated content");
w();
w("Generated by `packages/learning/scripts/samples.ts`. Every question below comes from a question family and passed the family's independent check; none is educator-reviewed.");
w();
for (const f of FAMILIES.keys()) {
  const s = familySpec(f);
  if (!s) continue;
  w(`## ${f}: ${s.title}`);
  w();
  w(`Skill \`${s.competency}\` · pool ${s.poolSize} · difficulty ${s.difficulty["1"]}/${s.difficulty["2"]}/${s.difficulty["3"]} · fingerprint \`${s.fingerprint}\`${s.teach ? ` · idea: ${s.teach.idea}` : ""}`);
  w();
  for (const id of s.examples.slice(0, 3)) {
    const q = question(id);
    const p = problemOf(id)!;
    w(`- \`${id}\`: ${q.prompt}${q.options ? ` Options: ${q.options.map((o, i) => `${"ABCD"[i]} ${o}`).join("; ")}.` : ""} **Answer: ${q.answer}.** Steps: ${p.steps.map((st) => explainStep(p, st)).join("; ")}.`);
    for (const b of p.bugs.slice(0, 3)) w(`  - if ${b.predict === null ? "—" : JSON.stringify(b.predict)}: ${b.says}`);
  }
  w();
}
for (const c of ["MATH.number.multi-multiplication", "MATH.algebra.factorisation"]) {
  const m = modules.find((x) => x.competency === c)!;
  w(`## Template module: ${m.title}`);
  w();
  w(`Pool: ${JSON.stringify(poolDepth(m)?.counts)}.`);
  w();
  for (const s of [...m.chapter.map((x) => ({ ...x, h: "Chapter" })), ...m.strategies.flatMap((st) => st.screens.map((x) => ({ ...x, h: `Strategy “${st.title}” (${st.kind})` })))]) {
    w(`**${s.h}: ${s.title}.** ${s.text.join(" ")}${s.math ? ` — ${s.math.join(" / ")}` : ""}${s.tip ? ` (Tip: ${s.tip})` : ""}`);
    w();
  }
}
writeFileSync(join(import.meta.dirname, "../../../docs/learning-year/GENERATED_SAMPLES.md"), L.join("\n") + "\n");
