/**
 * The mathematics coverage matrix (compiler@1), for every grade and board:
 *   content/learning/coverage-matrix.v1.json   machine-readable: every requirement, every competency's 12 criteria
 *   docs/mathematics/COVERAGE_MATRIX.md         the same, summarised for people
 *
 *   node --import tsx packages/learning/scripts/compile-coverage.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CLASS_LABEL, CRITERIA, checkCompetency, compileRelease, COMPILER_POLICY, priorities, type RequirementClass, type RequirementRow } from "../src/compiler";
import { boardReleases } from "../src/board-releases";
import { FAMILIES, pool } from "../src/families";
import { graph } from "../src/graph";
import { modules } from "../src/content";
import { writtenTasks } from "../src/written";
import expansion from "../../../content/learning/competency-expansion.v1.json";

const root = join(import.meta.dirname, "../../..");
const rows: RequirementRow[] = boardReleases.flatMap(compileRelease);
const classes = Object.keys(CLASS_LABEL) as RequirementClass[];
const count = (rs: RequirementRow[]) => Object.fromEntries(classes.map((k) => [k, rs.filter((r) => r.class === k).length])) as Record<RequirementClass, number>;
const comps = [...new Set(rows.flatMap((r) => r.competencies))].sort();
const checks = comps.map(checkCompetency);
const byGrade = boardReleases.map((r) => ({ release: r.id, board: r.source.board, grade: r.grade, title: r.title, chapters: r.subjects[0].chapters.length, requirements: rows.filter((x) => x.release.startsWith(`${r.id}@`)).length, classes: count(rows.filter((x) => x.release.startsWith(`${r.id}@`))) }));
const fams = [...FAMILIES.values()].filter((f) => f.domain);
const typeMix = fams.reduce((m, f) => ((m[f.type] = (m[f.type] ?? 0) + 1), m), {} as Record<string, number>);
const prio = priorities(rows);
const allComps = graph.competencies.filter((c) => !c.partOf);
const out = {
  schema: "coverage-matrix@1",
  policy: COMPILER_POLICY,
  note: "GENERATED by packages/learning/scripts/compile-coverage.ts. Requirements are the outcomes of the CBSE (NCERT) and Tamil Nadu State Board releases, Grades 1–12 (content/learning/syllabus). Nothing here is educator-approved unless criterion 12 says so.",
  criteria: CRITERIA,
  classes: CLASS_LABEL,
  summary: {
    requirements: rows.length,
    classes: count(rows),
    competenciesRequired: comps.length,
    competenciesComplete: checks.filter((c) => c.complete).length,
    competenciesApproved: checks.filter((c) => c.met.review).length,
    graph: { competencies: allComps.length, inventory: allComps.filter((c) => c.origin === "inventory").length, expansion: allComps.filter((c) => c.origin === "expansion").length, relations: expansion.relations.length, disputed: expansion.disputed.length },
    families: { count: fams.length, problems: fams.reduce((n, f) => n + pool(f.id).items.length, 0), answerTypes: typeMix, withPictures: fams.filter((f) => f.figure).length, withEverydayForm: fams.filter((f) => f.word).length, withAlternatives: fams.filter((f) => f.teach?.alternatives?.length).length },
    modules: modules.length,
    writtenTasks: writtenTasks.length,
  },
  grades: byGrade,
  competencies: checks,
  requirements: rows,
  priorities: prio,
};
writeFileSync(join(root, "content/learning/coverage-matrix.v1.json"), JSON.stringify(out, null, 1) + "\n");
const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : "–");
const md: string[] = [
  "# Mathematics coverage matrix (Grades 1–12, CBSE and Tamil Nadu State Board)",
  "",
  `GENERATED by \`packages/learning/scripts/compile-coverage.ts\` (${COMPILER_POLICY}). Machine-readable: \`content/learning/coverage-matrix.v1.json\`.`,
  "",
  "**Nothing is educator-approved.** \"Implemented, awaiting educator review\" means engineering-complete: every one of criteria 1–11 is met by the content itself. It is not approval, and it is not release.",
  "",
  "## Requirements by class",
  "",
  "| Class | Requirements | Share |",
  "|---|---|---|",
  ...classes.map((k) => `| ${CLASS_LABEL[k]} | ${out.summary.classes[k]} | ${pct(out.summary.classes[k], rows.length)} |`),
  `| **All** | **${rows.length}** | |`,
  "",
  `Competencies the curricula require: **${comps.length}**; complete (criteria 1–11): **${out.summary.competenciesComplete}**; educator-approved: **${out.summary.competenciesApproved}**.`,
  "",
  "## By board and grade",
  "",
  `| Board | Grade | Chapters | Requirements | ${classes.map((k) => CLASS_LABEL[k]).join(" | ")} |`,
  `|---|---|---|---|${classes.map(() => "---").join("|")}|`,
  ...byGrade.map((g) => `| ${g.board?.startsWith("CBSE") ? "CBSE" : "Tamil Nadu"} | ${g.grade} | ${g.chapters} | ${g.requirements} | ${classes.map((k) => g.classes[k]).join(" | ")} |`),
  "",
  "## The twelve criteria, across required competencies",
  "",
  "| Criterion | Met | Not met |",
  "|---|---|---|",
  ...CRITERIA.map((k, i) => `| ${i + 1}. ${k} | ${checks.filter((c) => c.met[k]).length} | ${checks.filter((c) => !c.met[k]).length} |`),
  "",
  "## Question families",
  "",
  `${out.summary.families.count} families, ${out.summary.families.problems} problems in release pools. Answer types: ${Object.entries(typeMix).map(([k, v]) => `${k} ${v}`).join(", ")}. With a picture: ${out.summary.families.withPictures}; with an everyday (transfer) form: ${out.summary.families.withEverydayForm}; with alternative explanations: ${out.summary.families.withAlternatives}. Written (educator-marked) tasks: ${writtenTasks.length}.`,
  "",
  "## Graph",
  "",
  `${out.summary.graph.competencies} competencies: ${out.summary.graph.inventory} from the original inventory (ids unchanged) and ${out.summary.graph.expansion} added by the curriculum expansion (expansion@1); ${out.summary.graph.relations} expansion relations; ${out.summary.graph.disputed} disputed prerequisites listed for educator review and not followed.`,
  "",
  "## What to build next (dependency order, then demand)",
  "",
  "| Competency | Grades | Requirements waiting | Missing |",
  "|---|---|---|---|",
  ...prio.slice(0, 60).map((p) => `| ${p.name} (\`${p.id}\`) | ${p.grades.join("–")} | ${p.demand} | ${p.missing.filter((m) => m !== "review").join(", ") || "review"} |`),
  prio.length > 60 ? `\n…and ${prio.length - 60} more in the JSON.` : "",
  "",
];
writeFileSync(join(root, "docs/mathematics/COVERAGE_MATRIX.md"), md.join("\n") + "\n");
console.log(`requirements ${rows.length}: ${classes.map((k) => `${k} ${out.summary.classes[k]}`).join(", ")}; competencies required ${comps.length}, complete ${out.summary.competenciesComplete}, approved ${out.summary.competenciesApproved}`);
