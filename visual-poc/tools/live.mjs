// Review aid: run the scene for real (requestAnimationFrame, audio unlocked by a click) and report.
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const [, , size = "1280x860", secs = "6", out = "/tmp/live.png"] = process.argv;
const [w, h] = size.split("x").map(Number);
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist", "--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: 1 });
const errors = [];
page.on("console", (m) => { if ((m.type() === "error" || m.type() === "warning") && !m.text().includes("Failed to load resource") && !m.text().includes("GPU stall")) errors.push(m.type() + ": " + m.text()); });
page.on("pageerror", (e) => errors.push("PAGEERROR " + e.message));
await page.goto("file://" + join(root, "dist/standalone.html"));
await page.waitForFunction(() => window.__poc, null, { timeout: 30000 });
await page.screenshot({ path: out.replace(".png", "-before.png") });
await page.click("#play");
await page.waitForTimeout(+secs * 1000);
await page.screenshot({ path: out });
console.log(await page.evaluate(() => ({ phase: window.__poc.phase, time: +window.__poc.time.toFixed(2), fps: document.querySelector("#fps").textContent, line: document.querySelector("#line").textContent, overflow: document.documentElement.scrollWidth - document.documentElement.clientWidth })), errors.length ? errors : "no errors");
await browser.close();
