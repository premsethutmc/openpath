/**
 * Seeded replay harness (synthetic-harness@1). Runs one synthetic learner through the real A3 learning journey via the adapter port and returns
 * three SEPARATE records: what crossed the boundary (learner-visible frames and learner actions), the learner's hidden trace, and OpenPath's own
 * records and state read AFTER the run for the report (the learner never sees the latter).
 */
import { createHash } from "node:crypto";
import { moduleFor } from "../../../packages/learning/src/content";
import { SimClock } from "./clock";
import { SliceFlow } from "../../../frontend/src/journey/flow";
import { A3Port, type JourneyPort, type LearnerAction, type PortFrame } from "./adapter";
import { SyntheticLearner, type HiddenEvent } from "./learner";
import type { Profile } from "./model";

export const HARNESS_VERSION = "synthetic-harness@1" as const;
export const COMPETENCY = "MATH.algebra.linear-equations";
export const SIM_START = Date.parse("2026-03-02T09:00:00Z");
export interface Crossing { n: number; frame: PortFrame; action: LearnerAction | null }
export interface RunResult {
  harness: typeof HARNESS_VERSION; profile: string; seed: number; schedule: number[];
  boundary: Crossing[]; hidden: HiddenEvent[];
  openpath: { records: unknown[]; evidence: unknown; terminatedSessions: number };
  digests: { boundary: string; hidden: string; openpath: string };
}
const digest = (x: unknown) => createHash("sha256").update(JSON.stringify(x)).digest("hex").slice(0, 16);

/** drive one session until OpenPath ends it (summary) or the interaction bound */
export function drive(port: JourneyPort, learner: SyntheticLearner, out: Crossing[], max = 60): boolean {
  let teaching: { title: string; text: string[] } | null = null;
  for (let i = 0; i < max; i++) {
    const f = port.frame();
    let a: LearnerAction | null = null;
    if (f.stage === "summary") { out.push({ n: out.length + 1, frame: f, action: null }); return true; }
    if (f.stage === "question") { const r = learner.respond(f.question); a = r.kind === "hint" ? { type: "hint" } : { type: "answer", value: r.answer, ...(r.working.length ? { working: r.working } : {}) }; }
    else if (f.stage === "feedback") { learner.observeFeedback(f.feedback); a = { type: "continue" }; }
    else if (f.stage === "teaching") { teaching = teaching && teaching.title === f.teaching.title ? { title: teaching.title, text: [...teaching.text, f.teaching.text] } : { title: f.teaching.title, text: [f.teaching.text] }; a = { type: "continue" }; }
    out.push({ n: out.length + 1, frame: f, action: a });
    const next = port.act(a!);
    // the explanation is over when the flow leaves it: the learner has seen all of it
    if (teaching && f.stage === "teaching" && (next.stage !== "teaching" || (next.stage === "teaching" && next.teaching.title !== teaching.title))) { learner.observeTeaching({ title: teaching.title, text: teaching.text.join("\n") }); teaching = null; }
  }
  return false;
}
/** one learner, a schedule of return visits (days after the previous visit), a seed */
export function runJourney(profile: Profile, o: { seed?: number; schedule?: number[]; max?: number; learnerId?: string } = {}): RunResult {
  const seed = o.seed ?? profile.seed, schedule = o.schedule ?? [1, 8, 3, 8];
  const clock = new SimClock(SIM_START);
  const learner = new SyntheticLearner(profile, clock, seed);
  const entry = moduleFor(COMPETENCY)!.diagnostics[0];   // OpenPath's own entry question to the skill
  const flow = new SliceFlow(entry, o.learnerId ?? `synthetic-${profile.id}-${seed}`, SIM_START);
  const port = new A3Port(flow);
  const boundary: Crossing[] = [];
  let ended = drive(port, learner, boundary, o.max) ? 1 : 0;
  for (const d of schedule) { learner.advance(d); port.later(d); ended += drive(port, learner, boundary, o.max) ? 1 : 0; }
  const st = flow.session.state();
  const openpath = { records: flow.session.events.map((e) => ({ ...(e as object) })), evidence: st.evidence(COMPETENCY), terminatedSessions: ended };
  const hidden = learner.hiddenTrace();
  // OpenPath's record ids are generated by OpenPath itself (not by the simulator); they are replaced by their order of first appearance
  const ids = new Map<string, string>();
  const strip = (x: unknown) => JSON.parse(JSON.stringify(x, (_k, v) => (typeof v === "string" && /^(?:lr-|dec:lr-)/.test(v) ? (ids.get(v) ?? (ids.set(v, `#${ids.size}`), ids.get(v))) : v)));
  return { harness: HARNESS_VERSION, profile: `${profile.id}@${profile.version}`, seed, schedule, boundary, hidden, openpath,
    digests: { boundary: digest(boundary), hidden: digest(hidden), openpath: digest(strip(openpath)) } };
}
