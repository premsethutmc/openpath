"""Writes DATASETS.md (tables computed from the frozen files + verification results). Usage: summarize_datasets.py FROZEN_DIR VERIFY_JSON OUT_MD"""
import json, sys, os
from collections import Counter
d, vj, out = sys.argv[1:4]
L = lambda n: json.load(open(os.path.join(d, n)))
man = L('manifest.json'); ver = json.load(open(vj)); w = []
w.append('# Frozen datasets (generated file — do not edit by hand)\n')
w.append(f"Generated by `gen_domain_sets.py`; SymPy {man['sympy']}. Seeds: " + ', '.join(f"{k} {v}" for k, v in man['seeds'].items()) + '.\n')
w.append('| File | Items | SHA-256 | Verified by the SymPy-free Fraction oracle |\n|---|---|---|---|')
for n, v in man['files'].items():
    r = ver.get(n, {}); w.append(f"| `{n}` | {v['items']} | `{v['sha256']}` | {r.get('items', '?') - r.get('withProblems', 0) if r else '?'}/{r.get('items', '?')} agree |")
w.append('')
sets = {n: L(n) for n in ['dev.json', 'eval.json', 'holdout.json']}
texts = {n: {i['text'] for i in v} for n, v in sets.items()}; texts['unsupported.json'] = {i['text'] for i in L('unsupported.json')}
names = list(texts)
w.append('## Overlap between files (identical equation text)\n')
w.append('| | ' + ' | '.join(names) + ' |\n|---|' + '---|' * len(names))
for a in names: w.append(f"| {a} | " + ' | '.join(str(len(texts[a] & texts[b])) if a != b else str(len(texts[a])) for b in names) + ' |')
w.append('\nDiagonal = size; off-diagonal must be 0.\n')
w.append('## Supported sets: what each contains (oracle-assigned tags; one equation can carry several)\n')
tags = ['unique-solution', 'no-solution', 'restricted-identity', 'removable', 'extraneous-candidate', 'all-candidates-rejected', 'extraneous-and-valid-root', 'multi-excluded', 'multi-step', 'plain']
w.append('| Tag | ' + ' | '.join(sets) + ' |\n|---|' + '---|' * len(sets))
def tg(i):
    t = list(i['tags'])
    if i['class'] == 'unique': t.append('unique-solution')
    if not i['tags'] and i['class'] == 'unique': t.append('plain')
    return t
for t in tags: w.append(f"| {t} | " + ' | '.join(str(sum(t in tg(i) for i in v)) for v in sets.values()) + ' |')
w.append('| items | ' + ' | '.join(str(len(v)) for v in sets.values()) + ' |')
w.append('\n| Excluded values per equation | ' + ' | '.join(sets) + ' |\n|---|' + '---|' * len(sets))
for k in [1, 2, 3]: w.append(f"| {k}{'+' if k == 3 else ''} | " + ' | '.join(str(sum((len(i['excluded']) >= 3 if k == 3 else len(i['excluded']) == k) for i in v)) for v in sets.values()) + ' |')
w.append('\n| Recipe family | ' + ' | '.join(sets) + ' |\n|---|' + '---|' * len(sets))
for rname in sorted({i['recipe'] for v in sets.values() for i in v}): w.append(f"| `{rname}` | " + ' | '.join(str(sum(i['recipe'] == rname for i in v)) for v in sets.values()) + ' |')
w.append('\nThe holdout contains four recipe families (`h_*`) that appear in neither dev nor eval, so it tests structure as well as new numbers. `dev.json` also holds the six previously refused `(a*x)/x = c` style equations (tag `legacy-refused`) as visible regression cases; they are not special-cased anywhere.\n')
un = L('unsupported.json')
w.append('## Unsupported / out-of-scope set\n')
w.append(f"{len(un)} equations the oracle places outside the stated scope. Expected behaviour: refuse, with a reason code from the oracle's list for that equation.\n")
w.append('| Primary reason | Items |\n|---|---|'); 
for k, v in sorted(Counter(i['reasons'][0] for i in un).items()): w.append(f"| `{k}` | {v} |")
adv = L('adversarial.json'); cl = L('claims.json')
w.append('\n## Adversarial transitions (state → state)\n')
w.append(f"{len(adv)} transitions; validity labelled by the oracle (`intent` records what the generator meant; the oracle's label wins).\n")
w.append('| Kind | Intent | Oracle: invalid | Oracle: valid |\n|---|---|---|---|')
agg = {}
for t in adv: agg.setdefault((t['kind'], t['intent']), [0, 0])[0 if not t['expectedValid'] else 1] += 1
for (k, i), (bad, ok) in sorted(agg.items()): w.append(f"| {k} | {i} | {bad} | {ok} |")
tot_bad = sum(not t['expectedValid'] for t in adv); w.append(f"| **total** | | **{tot_bad}** | **{len(adv) - tot_bad}** |")
mism = sum((t['intent'] == 'illegal' and t['expectedValid']) or (t['intent'] == 'legal' and not t['expectedValid']) for t in adv)
w.append(f"\nGenerator intent contradicted by the oracle in {mism} transitions (kept, with the oracle's label). Invalid-reason counts: " + ', '.join(f"{k} {v}" for k, v in sorted(Counter(r for t in adv for r in t['reasons']).items())) + '.\n')
w.append('## Claimed solution sets\n')
w.append(f"{len(cl)} claims; {sum(not c['expectedValid'] for c in cl)} wrong, {sum(c['expectedValid'] for c in cl)} right.\n")
w.append('| Kind | Wrong | Right |\n|---|---|---|')
ag = {}
for c in cl: ag.setdefault(c['kind'], [0, 0])[1 if c['expectedValid'] else 0] += 1
for k, (bad, ok) in sorted(ag.items()): w.append(f"| {k} | {bad} | {ok} |")
open(out, 'w').write('\n'.join(w) + '\n')
print('wrote', out)
