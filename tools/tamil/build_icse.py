def graphemes(word):
    out = []
    for ch in word:
        if out and (0x0BBE <= ord(ch) <= 0x0BCD or ord(ch) == 0x0BD7):
            out[-1] += ch
        else:
            out.append(ch)
    return out


def check(topics):
    errors, ids = [], set()
    for t in topics:
        if len(t["questions"]) < 4:
            errors.append(f"{t['id']}: too few questions")
        for q in t["questions"]:
            if q["id"] in ids:
                errors.append(f"duplicate {q['id']}")
            ids.add(q["id"])
            if q["answer"] not in q["options"] or len(set(q["options"])) != len(q["options"]) or len(q["options"]) < 2:
                errors.append(f"{q['id']}: bad options {q['options']}")
    return errors


