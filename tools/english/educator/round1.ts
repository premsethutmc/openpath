/**
 * First-round educator review (pilot validation v1): the three pilot competencies only, in review order, as a subset
 * of the consolidated package (educator-review-v1). Records keep their ids and fingerprints, so round-1 decisions are
 * read, reconciled and adjudicated by the existing workflow (review.ts reconcile / decisions) without change.
 *
 *   node tools/english/educator/round1.ts export [--check]
 *        write docs/product/essay-learning/educator-review-v1/round-1/ (records.json, round-1.csv,
 *        reviewer-A/decisions.csv, reviewer-B/decisions.csv, ORDER.md); --check: is it current?
 *        The two workbooks are built by: python3 tools/english/educator/workbook.py build-round1
 *   node tools/english/educator/round1.ts progress <A.csv> <B.csv>
 *        for the coordinator: how far each reviewer has got, WITHOUT showing any decision, and whether the files are
 *        independent (different reviewer ids, one reviewer per file). Run reconcile only when both are complete.
 *
 * Order, per competency: the competency definition (with prerequisites, curriculum mappings and the provisional
 * target), then its lessons in ladder order, then its questions in the order a learner meets them (diagnostic,
 * guided practice, independent check, later check, delayed retention). Each question carries its pilot priority:
 * "required" when the locked pilot policy (one later check) needs it for one complete sequence, "optional" when it
 * serves only an additional later check. Nothing here approves, promotes or changes content.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadAppEssayContext } from "../essay-load.ts";
import { REPO } from "../load.ts";
import { toCsv } from "../pilot/review.ts";
import { pilotMatrix } from "./pilot-matrix.ts";
import { buildInventory, DECISION_COLUMNS, PACKAGE_DIR, readDecisions, type ReviewRecord } from "./review.ts";

export const ROUND1_DIR = join(PACKAGE_DIR, "round-1");
export const ROUND1_VERSION = "educator-review@1/round-1";

export interface Round1Entry {
  review_order: number;
  pilot_competency: string;
  pilot_stage: string;
  pilot_priority: "required" | "optional" | "definition" | "lesson";
  record: ReviewRecord;
}

const STAGE_NAMES: Record<string, string> = {
  "2.": "diagnostic",
  "4.": "guided practice",
  "5.": "independent check",
  "6.": "later check",
  "7.": "delayed retention",
};

export function round1(): Round1Entry[] {
  const inv = buildInventory();
  const by = new Map(inv.records.map((r) => [`${r.kind}:${r.id}`, r]));
  const get = (kind: string, id: string) => {
    const r = by.get(`${kind}:${id}`);
    if (!r) throw new Error(`round 1: ${kind} ${id} is not in the consolidated package`);
    return r;
  };
  const { checkItems } = loadAppEssayContext().policy;
  const out: Round1Entry[] = [];
  const seen = new Set<string>();
  const push = (e: Omit<Round1Entry, "review_order">) => {
    const k = `${e.record.kind}:${e.record.id}`;
    if (seen.has(k)) return;
    seen.add(k);
    out.push({ review_order: out.length + 1, ...e });
  };
  for (const row of pilotMatrix()) {
    const cap = row.competency;
    push({ pilot_competency: cap, pilot_stage: "competency definition", pilot_priority: "definition", record: get("competency", cap) });
    for (const id of row.requiresEducatorApproval.lessons) push({ pilot_competency: cap, pilot_stage: "lesson", pilot_priority: "lesson", record: get("lesson", id) });
    for (const s of row.stages) {
      const name = STAGE_NAMES[s.stage.slice(0, 2)];
      if (!name) continue;
      // the locked pilot policy needs every item of each stage except the later-check allowance beyond one check
      const needed = s.stage.startsWith("6.") ? checkItems : s.required;
      s.ifSupplementApproved.items.forEach((id, k) => push({ pilot_competency: cap, pilot_stage: name, pilot_priority: k < needed ? "required" : "optional", record: get("question", id) }));
    }
  }
  return out;
}

const COLUMNS = ["review_order", "pilot_competency", "pilot_stage", "pilot_priority", "record_kind", "record_id", "version", "fingerprint", "title_or_question", "set", "evidence_status"];

function title(r: ReviewRecord): string {
  if (r.kind === "question") return r.question;
  if (r.kind === "lesson") return r.title;
  return r.name;
}

function orderMarkdown(entries: Round1Entry[]): string {
  const count = (f: (e: Round1Entry) => boolean) => entries.filter(f).length;
  const lines = [
    "# Round 1: review order",
    "",
    "Generated by `node tools/english/educator/round1.ts export`; do not edit by hand. Review the rows in this order.",
    "",
    `${entries.length} records: ${count((e) => e.record.kind === "competency")} competency definitions, ${count((e) => e.record.kind === "lesson")} lesson parts, ${count((e) => e.record.kind === "question")} questions (${count((e) => e.pilot_priority === "required")} required by the locked pilot policy, ${count((e) => e.pilot_priority === "optional")} only for an optional additional later check).`,
    "",
    "| # | Competency | Stage | Priority | Record | Set |",
    "|---:|---|---|---|---|---|",
  ];
  for (const e of entries) {
    const set = "set" in e.record ? e.record.set : "";
    lines.push(`| ${e.review_order} | ${e.pilot_competency.split(".").pop()} | ${e.pilot_stage} | ${e.pilot_priority} | \`${e.record.id}\` | ${set} |`);
  }
  lines.push("");
  return lines.join("\n");
}

export function exportRound1(dir = ROUND1_DIR): Map<string, string> {
  const entries = round1();
  const files = new Map<string, string>();
  files.set("records.json", JSON.stringify({ schema: "educator-review-round@1", round: ROUND1_VERSION, counts: { records: entries.length, competencies: entries.filter((e) => e.record.kind === "competency").length, lessons: entries.filter((e) => e.record.kind === "lesson").length, questions: entries.filter((e) => e.record.kind === "question").length }, entries }, null, 1) + "\n");
  files.set("round-1.csv", "﻿" + toCsv(COLUMNS, entries.map((e) => [String(e.review_order), e.pilot_competency, e.pilot_stage, e.pilot_priority, e.record.kind, e.record.id, String(e.record.version), e.record.fingerprint, title(e.record), "set" in e.record ? e.record.set : "", "evidence_status" in e.record ? e.record.evidence_status : e.record.target_status])));
  const template = "﻿" + toCsv([...DECISION_COLUMNS], entries.map((e) => [e.record.kind, e.record.id, String(e.record.version), e.record.fingerprint, "", "", "", "", "", ""]));
  files.set("reviewer-A/decisions.csv", template);
  files.set("reviewer-B/decisions.csv", template);
  files.set("ORDER.md", orderMarkdown(entries));
  for (const [f, text] of files) {
    mkdirSync(join(dir, f, ".."), { recursive: true });
    writeFileSync(join(dir, f), text);
  }
  return files;
}

/** Completion per reviewer file, without revealing any decision. */
export function progress(csvs: string[]): { files: { reviewers: string[]; decided: number; of: number; problems: number }[]; independent: boolean; complete: boolean; notes: string[] } {
  const entries = round1();
  const records = entries.map((e) => e.record);
  const files = csvs.map((csv) => {
    const r = readDecisions(csv, records);
    return { reviewers: [...new Set(r.rows.map((x) => x.reviewer))], decided: new Set(r.rows.map((x) => `${x.kind}:${x.id}`)).size, of: records.length, problems: r.problems.length };
  });
  const notes: string[] = [];
  files.forEach((f, k) => {
    if (f.reviewers.length > 1) notes.push(`file ${k + 1} has more than one reviewer id: each reviewer works in their own file`);
  });
  const ids = files.flatMap((f) => f.reviewers);
  if (new Set(ids).size !== ids.length) notes.push("the same reviewer id appears in two files: the reviews are not independent");
  const independent = files.length >= 2 && notes.length === 0;
  const complete = files.length >= 2 && files.every((f) => f.decided === f.of && f.problems === 0);
  if (!complete) notes.push("not complete: do not reconcile or show either reviewer the other's file yet");
  return { files, independent, complete, notes };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, ...args] = process.argv.slice(2);
  if (cmd === "export") {
    if (args.includes("--check")) {
      const fresh = exportRound1(join(REPO, "tools", "english", "out", "round1-check"));
      const stale = [...fresh].filter(([f, text]) => !existsSync(join(ROUND1_DIR, f)) || readFileSync(join(ROUND1_DIR, f), "utf8") !== text).map(([f]) => f);
      if (stale.length) {
        console.error(`round-1 is not current: ${stale.join(", ")} (run: node tools/english/educator/round1.ts export)`);
        process.exit(1);
      }
      console.log("round-1 is current");
    } else {
      const f = exportRound1();
      console.log(`wrote ${[...f.keys()].join(", ")}`, JSON.parse(f.get("records.json")!).counts);
    }
  } else if (cmd === "progress" && args.length >= 2) {
    console.log(JSON.stringify(progress(args.map((f) => readFileSync(f, "utf8"))), null, 1));
  } else {
    console.error("usage: round1.ts export [--check] | progress <A.csv> <B.csv>");
    process.exit(2);
  }
}
