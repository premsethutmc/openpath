/**
 * Item-by-item educator review of the 30 proposed plural-noun questions (H-V4). A subset of the consolidated package
 * (educator-review-v1, set "proposed-plurals"), in review order: by sub-skill, and within each sub-skill in the order a
 * learner meets them (diagnostic, independent ×2, transfer, delayed retention). Records keep their ids and content
 * fingerprints, so decisions go through the existing workflow (review.ts reconcile / decisions, third-reviewer
 * adjudication) unchanged.
 *
 *   node tools/english/educator/round-plurals.ts export [--check]
 *        write docs/product/essay-learning/educator-review-v1/round-plurals/ (records.json, round-plurals.csv,
 *        reviewer-A/decisions.csv, reviewer-B/decisions.csv, ORDER.md); --check: is it current?
 *        Workbooks: python3 tools/english/educator/workbook.py build-plurals
 *   node tools/english/educator/round-plurals.ts progress <A.csv> <B.csv>
 *        completion per reviewer file, without showing any decision.
 *
 * Nothing here approves, promotes or changes content. An approved question becomes eligible for verification only
 * through a separate, owner-approved content release that marks that exact version "validated" with its released_at.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO } from "../load.ts";
import { toCsv } from "../pilot/review.ts";
import { loadPluralManifest, PLURAL_COVERAGE } from "../supplement/plurals.ts";
import { buildInventory, DECISION_COLUMNS, PACKAGE_DIR, readDecisions, type ReviewRecord } from "./review.ts";

export const PLURALS_ROUND_DIR = join(PACKAGE_DIR, "round-plurals");
export const PLURALS_ROUND_VERSION = "educator-review@1/round-plurals";

const COVERAGE_NAMES: Record<string, string> = {
  regular: "Regular plurals (-s, -es, -ies, -ves)",
  irregular: "Irregular plurals",
  already_plural: "Already-plural nouns",
  number_plural: "Number + plural",
  quantifiers: "Quantifiers",
  countable_uncountable: "Countable and uncountable nouns",
};
const USES = ["diagnostic", "independent", "transfer", "retention"] as const;
const USE_NAMES: Record<string, string> = { diagnostic: "diagnostic", independent: "independent check", transfer: "transfer (correction in context)", retention: "delayed retention" };

export interface PluralEntry {
  review_order: number;
  coverage: string;
  coverage_name: string;
  proposed_use: string;
  record: ReviewRecord;
}

export function roundPlurals(): PluralEntry[] {
  const inv = buildInventory();
  const m = loadPluralManifest();
  const qs = inv.records.filter((r): r is Extract<ReviewRecord, { kind: "question" }> => r.kind === "question" && r.set === "proposed-plurals");
  const out: PluralEntry[] = [];
  for (const cov of PLURAL_COVERAGE)
    for (const use of USES)
      for (const r of qs.filter((q) => m.coverage[q.id] === cov && m.proposedUse[q.id] === use).sort((a, b) => a.id.localeCompare(b.id)))
        out.push({ review_order: out.length + 1, coverage: cov, coverage_name: COVERAGE_NAMES[cov] ?? cov, proposed_use: USE_NAMES[use], record: r });
  if (out.length !== qs.length) throw new Error(`round-plurals: ${qs.length - out.length} proposed plural questions have no coverage or use`);
  return out;
}

const COLUMNS = ["review_order", "coverage", "proposed_use", "record_kind", "record_id", "version", "fingerprint", "response_type", "question", "expected_answer", "difficulty_b", "evidence_status"];

function orderMarkdown(entries: PluralEntry[]): string {
  const lines = [
    "# Plural questions: review order",
    "",
    "Generated by `node tools/english/educator/round-plurals.ts export`; do not edit by hand. Review the rows in this order.",
    "",
    `${entries.length} questions: ${PLURAL_COVERAGE.length} sub-skills × (1 diagnostic, 2 independent, 1 transfer, 1 delayed retention); ${entries.filter((e) => e.record.kind === "question" && e.record.response_type === "constructed").length} constructed (typed), the rest recognition.`,
    "",
    "| # | Sub-skill | Proposed use | Record | Type | b |",
    "|---:|---|---|---|---|---:|",
  ];
  for (const e of entries) {
    const q = e.record as Extract<ReviewRecord, { kind: "question" }>;
    lines.push(`| ${e.review_order} | ${e.coverage_name} | ${e.proposed_use} | \`${q.id}\` | ${q.response_type} | ${q.difficulty_b} |`);
  }
  lines.push("");
  return lines.join("\n");
}

export function exportRoundPlurals(dir = PLURALS_ROUND_DIR): Map<string, string> {
  const entries = roundPlurals();
  const files = new Map<string, string>();
  files.set("records.json", JSON.stringify({ schema: "educator-review-round@1", round: PLURALS_ROUND_VERSION, counts: { records: entries.length, questions: entries.length }, entries }, null, 1) + "\n");
  files.set(
    "round-plurals.csv",
    "﻿" +
      toCsv(
        COLUMNS,
        entries.map((e) => {
          const q = e.record as Extract<ReviewRecord, { kind: "question" }>;
          return [String(e.review_order), e.coverage, e.proposed_use, q.kind, q.id, String(q.version), q.fingerprint, q.response_type, q.question, q.expected_answer, String(q.difficulty_b), q.evidence_status];
        }),
      ),
  );
  const template = "﻿" + toCsv([...DECISION_COLUMNS], entries.map((e) => [e.record.kind, e.record.id, String(e.record.version), e.record.fingerprint, "", "", "", "", "", ""]));
  files.set("reviewer-A/decisions.csv", template);
  files.set("reviewer-B/decisions.csv", template);
  files.set("ORDER.md", orderMarkdown(entries));
  for (const [f, text] of files) {
    mkdirSync(join(dir, f, ".."), { recursive: true });
    writeFileSync(join(dir, f), text);
  }
  return files;
}

/** Completion per reviewer file, without revealing any decision. */
export function pluralProgress(csvs: string[]) {
  const records = roundPlurals().map((e) => e.record);
  const files = csvs.map((csv) => {
    const r = readDecisions(csv, records);
    return { reviewers: [...new Set(r.rows.map((x) => x.reviewer))], decided: new Set(r.rows.map((x) => `${x.kind}:${x.id}`)).size, of: records.length, problems: r.problems.length };
  });
  const ids = files.flatMap((f) => f.reviewers);
  const independent = files.length >= 2 && files.every((f) => f.reviewers.length <= 1) && new Set(ids).size === ids.length;
  const complete = files.length >= 2 && files.every((f) => f.decided === f.of && f.problems === 0);
  return { files, independent, complete };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, ...args] = process.argv.slice(2);
  if (cmd === "export") {
    if (args.includes("--check")) {
      const fresh = exportRoundPlurals(join(REPO, "tools", "english", "out", "round-plurals-check"));
      const stale = [...fresh].filter(([f, text]) => !existsSync(join(PLURALS_ROUND_DIR, f)) || readFileSync(join(PLURALS_ROUND_DIR, f), "utf8") !== text).map(([f]) => f);
      if (stale.length) {
        console.error(`round-plurals is not current: ${stale.join(", ")} (run: node tools/english/educator/round-plurals.ts export)`);
        process.exit(1);
      }
      console.log("round-plurals is current");
    } else {
      const f = exportRoundPlurals();
      console.log(`wrote ${[...f.keys()].join(", ")}`, JSON.parse(f.get("records.json")!).counts);
    }
  } else if (cmd === "progress" && args.length >= 2) {
    console.log(JSON.stringify(pluralProgress(args.map((f) => readFileSync(f, "utf8"))), null, 1));
  } else {
    console.error("usage: round-plurals.ts export [--check] | progress <A.csv> <B.csv>");
    process.exit(2);
  }
}
